"""Automorphism Orbit Extraction and Symmetry Invariance Verifier for BB Codes.

Extracts the torus group action G = Z_l x Z_m on the circuit-level Detector
Error Model (DEM), partitions nodes and hyperedges into symmetry orbits,
classifies window boundary classes, and verifies automorphism invariance.
"""

from typing import List, Tuple, Dict, Set, Any, Optional
import numpy as np
from numpy.typing import NDArray
import stim

from orbit_tied_qnbp.circuits.bivariate_bicycle import BivariateBicycleCode


def boxplus_probabilities(probs: List[float]) -> float:
    r"""Exact Bernoulli XOR / boxplus combination of independent error probabilities.

    In F_2, if independent faults f in F_v induce identical detector and
    observable symptoms, the net error occurs if an odd number of them fire:
        p_v = 0.5 * (1 - \prod_{f in F_v} (1 - 2 p_f))
    """
    prod = 1.0
    for p in probs:
        p_clamped = min(max(p, 0.0), 0.5)
        prod *= (1.0 - 2.0 * p_clamped)
    p_merged = 0.5 * (1.0 - prod)
    return float(np.clip(p_merged, 1e-15, 1.0 - 1e-15))


class DemOrbitManager:
    """Manages automorphism orbits of a Bivariate Bicycle DEM under G = Z_l x Z_m.

    Attributes:
        code: BivariateBicycleCode instance.
        num_rounds: Number of syndrome extraction rounds in the circuit.
        l: Group dimension l.
        m: Group dimension m.
        group_order: Order of G (|G| = l * m).
        det_to_coord: Mapping from detector index to (round, check_type, x, y).
        coord_to_det: Mapping from (round, check_type, x, y) to detector index.
        fault_orbits: Array of orbit IDs for each error mechanism.
        num_fault_orbits: Total distinct fault orbits.
    """

    def __init__(
        self,
        code: BivariateBicycleCode,
        num_rounds: int,
        dem: stim.DetectorErrorModel,
        merge_collinear: bool = False,
        basis: str = "Z",
    ) -> None:
        """Initializes the DEM orbit manager and computes symmetry orbits.

        Args:
            code: BivariateBicycleCode instance.
            num_rounds: Number of syndrome extraction rounds.
            dem: Detector Error Model generated by Stim.
            merge_collinear: If True, aggregates collinear hyperedges sharing identical
                symptoms using exact Bernoulli XOR / boxplus.
            basis: Memory basis ('Z' or 'X') used to build the Stim circuit.
        """
        self.code = code
        self.num_rounds = num_rounds
        self.l = code.l
        self.m = code.m
        self.group_order = code.group_order
        self.dem = dem
        self.merge_collinear = merge_collinear
        self.basis = basis.upper()

        self.det_to_coord, self.coord_to_det = self._build_detector_coordinate_maps()
        self.shift_table = self._build_shift_lookup_table()
        self.parsed_errors = self._parse_dem_errors(merge_collinear=merge_collinear)
        self.fault_orbits, self.num_fault_orbits = self._compute_fault_orbits()

    def _build_shift_lookup_table(self) -> NDArray[np.int64]:
        """Precomputes lookup table of shape (num_detectors, l, m) for O(1) shifts."""
        num_dets = len(self.det_to_coord)
        table = np.zeros((num_dets, self.l, self.m), dtype=np.int64)
        for d in range(num_dets):
            r, ctype, x, y = self.det_to_coord[d]
            for a in range(self.l):
                for b in range(self.m):
                    table[d, a, b] = self.coord_to_det[(r, ctype, (x + a) % self.l, (y + b) % self.m)]
        return table

    def _build_detector_coordinate_maps(
        self,
    ) -> Tuple[Dict[int, Tuple[Any, str, int, int]], Dict[Tuple[Any, str, int, int], int]]:
        """Maps detector index to (round_id, check_type, x, y) and vice versa."""
        d2c: Dict[int, Tuple[Any, str, int, int]] = {}
        c2d: Dict[Tuple[Any, str, int, int], int] = {}
        idx = 0
        g = self.group_order
        m = self.m

        for r in range(self.num_rounds):
            if self.basis == "Z" or r > 0:
                for i in range(g):
                    coord = (r, "Z", i // m, i % m)
                    d2c[idx] = coord
                    c2d[coord] = idx
                    idx += 1
            if self.basis == "X" or r > 0:
                for i in range(g):
                    coord = (r, "X", i // m, i % m)
                    d2c[idx] = coord
                    c2d[coord] = idx
                    idx += 1

        for i in range(g):
            coord = ("terminal", self.basis, i // m, i % m)
            d2c[idx] = coord
            c2d[coord] = idx
            idx += 1

        return d2c, c2d

    def _parse_dem_errors(
        self,
        merge_collinear: bool = False,
    ) -> List[Tuple[float, Tuple[int, ...], Tuple[int, ...]]]:
        r"""Parses error mechanisms (probability, sorted detector symptoms, sorted observables).

        Args:
            merge_collinear: If True, aggregates collinear hyperedges sharing identical
                (detector, observable) symptoms using exact Bernoulli XOR / boxplus:
                p_v = 0.5 * (1 - \prod_{f} (1 - 2 p_f)).
        """
        raw_errors: Dict[Tuple[Tuple[int, ...], Tuple[int, ...]], List[float]] = {}
        for instruction in self.dem:
            if instruction.type == "error":
                p = float(instruction.args_copy()[0])
                dets = []
                obs = []
                for t in instruction.targets_copy():
                    if t.is_relative_detector_id():
                        dets.append(t.val)
                    elif t.is_logical_observable_id():
                        obs.append(t.val)
                key = (tuple(sorted(dets)), tuple(sorted(obs)))
                if key not in raw_errors:
                    raw_errors[key] = []
                raw_errors[key].append(p)

        errors = []
        if merge_collinear:
            for (dets, obs), probs in raw_errors.items():
                p_merged = boxplus_probabilities(probs)
                errors.append((p_merged, dets, obs))
        else:
            for (dets, obs), probs in raw_errors.items():
                for p in probs:
                    errors.append((p, dets, obs))
        return errors

    def shift_detector(self, det: int, a: int, b: int) -> int:
        """Applies spatial torus translation x^a y^b to a detector index in O(1)."""
        return int(self.shift_table[det, a, b])

    def _compute_fault_orbits(self) -> Tuple[NDArray[np.int64], int]:
        """Partitions all error mechanisms into orbits under the action of G."""
        num_errors = len(self.parsed_errors)
        fault_orbits = np.full(num_errors, -1, dtype=np.int64)

        # Index errors by (symptom_tuple, rounded_probability)
        symptom_map: Dict[Tuple[Tuple[int, ...], float], int] = {}
        for idx, (p, dets, _) in enumerate(self.parsed_errors):
            key = (dets, round(p, 12))
            symptom_map[key] = idx

        orbit_counter = 0
        s_table = self.shift_table
        for idx in range(num_errors):
            if fault_orbits[idx] != -1:
                continue
            # Seed new orbit
            current_orbit_id = orbit_counter
            orbit_counter += 1

            p, dets, _ = self.parsed_errors[idx]
            p_rounded = round(p, 12)
            det_len = len(dets)

            for a in range(self.l):
                for b in range(self.m):
                    if det_len == 1:
                        shifted_dets = (int(s_table[dets[0], a, b]),)
                    elif det_len == 2:
                        d0 = int(s_table[dets[0], a, b])
                        d1 = int(s_table[dets[1], a, b])
                        shifted_dets = (d0, d1) if d0 <= d1 else (d1, d0)
                    else:
                        shifted_dets = tuple(sorted(int(s_table[d, a, b]) for d in dets))

                    shifted_key = (shifted_dets, p_rounded)
                    if shifted_key in symptom_map:
                        match_idx = symptom_map[shifted_key]
                        if fault_orbits[match_idx] == -1:
                            fault_orbits[match_idx] = current_orbit_id

        return fault_orbits, orbit_counter

    def verify_automorphisms(self) -> Dict[str, Any]:
        """Verifies that all |G| = l * m torus shifts are strict DEM automorphisms.

        Returns:
            Dictionary containing verification statistics:
                - shifts_tested: Total shifts tested.
                - valid_shifts: Total shifts that preserve DEM error mechanisms.
                - num_errors: Total error mechanisms.
                - num_orbits: Total orbits.
                - compression_ratio: num_errors / num_orbits.

        Raises:
            AssertionError: If any shift fails to preserve DEM symptoms and priors.
        """
        symptom_map: Dict[Tuple[int, ...], List[Tuple[int, float]]] = {}
        for idx, (p, dets, _) in enumerate(self.parsed_errors):
            symptom_map.setdefault(dets, []).append((idx, p))

        num_errors = len(self.parsed_errors)
        valid_shifts = 0

        for a in range(self.l):
            for b in range(self.m):
                matched = 0
                for p, dets, _ in self.parsed_errors:
                    shifted_dets = tuple(sorted([self.shift_detector(d, a, b) for d in dets]))
                    if shifted_dets in symptom_map:
                        candidates = symptom_map[shifted_dets]
                        if any(abs(c_p - p) < 1e-10 for _, c_p in candidates):
                            matched += 1
                if matched == num_errors:
                    valid_shifts += 1
                else:
                    raise AssertionError(
                        f"Shift ({a}, {b}) is not an automorphism! "
                        f"Matched {matched}/{num_errors} error mechanisms."
                    )

        return {
            "shifts_tested": self.group_order,
            "valid_shifts": valid_shifts,
            "num_errors": num_errors,
            "num_orbits": self.num_fault_orbits,
            "compression_ratio": num_errors / max(1, self.num_fault_orbits),
        }

    def classify_window_boundary(
        self, window_start_round: int, window_end_round: int
    ) -> NDArray[np.int8]:
        """Classifies each error mechanism into window classes: 0=open_left, 1=interior, 2=open_right.

        Args:
            window_start_round: Starting syndrome extraction round index.
            window_end_round: Ending syndrome extraction round index.

        Returns:
            1D array of length num_errors containing class labels (0, 1, or 2).
        """
        classes = np.ones(len(self.parsed_errors), dtype=np.int8)  # default: interior (1)
        for idx, (_, dets, _) in enumerate(self.parsed_errors):
            touches_start = False
            touches_end = False
            for d in dets:
                r, _, _, _ = self.det_to_coord[d]
                if r == window_start_round:
                    touches_start = True
                elif r == window_end_round or r == "terminal":
                    touches_end = True
            if touches_start and not touches_end:
                classes[idx] = 0  # open_left
            elif touches_end and not touches_start:
                classes[idx] = 2  # open_right

        return classes


def verify_quotient_isomorphism(
    code_small: BivariateBicycleCode,
    code_large: BivariateBicycleCode,
    num_rounds: int = 3,
    error_rate: float = 0.003,
) -> Dict[str, Any]:
    """Verifies quotient DEM isomorphism G_DEM / (Z_l x Z_m) between two BB codes.

    Checks:
      1) Equal canonical orbit counts and identical (prob, check-orbit multiset)
         quotient profiles.
      2) When (l_large % l_small == 0) and (m_large % m_small == 0), verifies the
         covering epimorphism (x, y) -> (x mod l_small, y mod m_small) produces
         zero intra-fault detector collisions and zero missing targets.
    """
    circ_s = code_small.build_stim_circuit(rounds=num_rounds, error_rate=error_rate)
    dem_s = circ_s.detector_error_model(decompose_errors=False, approximate_disjoint_errors=True)
    mgr_s = DemOrbitManager(code_small, num_rounds, dem_s, merge_collinear=False)

    circ_l = code_large.build_stim_circuit(rounds=num_rounds, error_rate=error_rate)
    dem_l = circ_l.detector_error_model(decompose_errors=False, approximate_disjoint_errors=True)
    mgr_l = DemOrbitManager(code_large, num_rounds, dem_l, merge_collinear=False)

    def _profile(mgr: DemOrbitManager) -> List[Tuple[float, Tuple[Tuple[str, str], ...]]]:
        profs = []
        for oid in range(mgr.num_fault_orbits):
            idx = int(np.where(mgr.fault_orbits == oid)[0][0])
            p, dets, _ = mgr.parsed_errors[idx]
            c_multiset = tuple(sorted((str(mgr.det_to_coord[d][0]), mgr.det_to_coord[d][1]) for d in dets))
            profs.append((round(p, 10), c_multiset))
        return sorted(profs)

    prof_s = _profile(mgr_s)
    prof_l = _profile(mgr_l)
    profile_match = (mgr_s.num_fault_orbits == mgr_l.num_fault_orbits) and (prof_s == prof_l)

    covering_verified = False
    collisions = -1
    missing = -1
    if code_large.l % code_small.l == 0 and code_large.m % code_small.m == 0:
        small_set = {(tuple(sorted(dets)), round(p, 10)) for p, dets, _ in mgr_s.parsed_errors}
        collisions = 0
        missing = 0
        for p, dets, _ in mgr_l.parsed_errors:
            proj = []
            for d in dets:
                r, tp, x, y = mgr_l.det_to_coord[d]
                proj.append(mgr_s.coord_to_det[(r, tp, x % code_small.l, y % code_small.m)])
            if len(set(proj)) != len(proj):
                collisions += 1
            if (tuple(sorted(proj)), round(p, 10)) not in small_set:
                missing += 1
        covering_verified = (collisions == 0) and (missing == 0)

    return {
        "orbits_small": mgr_s.num_fault_orbits,
        "orbits_large": mgr_l.num_fault_orbits,
        "quotient_profile_match": profile_match,
        "covering_epimorphism_applicable": (code_large.l % code_small.l == 0 and code_large.m % code_small.m == 0),
        "covering_epimorphism_exact": covering_verified,
        "collisions": collisions,
        "missing": missing,
    }


def compute_logical_translation_action(
    code: BivariateBicycleCode, a: int, b: int, basis: str = "Z"
) -> Dict[str, Any]:
    """Computes the GF(2)-linear action M in GL(k, F_2) of torus shift (a, b) on logical space."""
    from orbit_tied_qnbp.utils.gf2 import gf2_rank

    p_L = code._get_perm(a, b)
    perm_q = np.concatenate([p_L, code.group_order + p_L])
    l_mat = code.lz if basis.upper() == "Z" else code.lx
    h_mat = code.hz if basis.upper() == "Z" else code.hx
    k = code.num_logicals
    n = code.num_data_qubits

    # Solve L_shifted[j] == M[j, :] @ L_mat (mod rowspace(H)) over GF(2)
    # Augmented basis rows = [H; L_mat]
    basis_rows = np.vstack([h_mat, l_mat])
    r_h = h_mat.shape[0]
    m_mat = np.zeros((k, k), dtype=np.uint8)
    shifted = l_mat[:, perm_q]

    # Precompute GF(2) solver via Gaussian elimination on basis_rows.T
    mat_t = basis_rows.T.copy()  # (n, r_h + k)
    for j in range(k):
        target = shifted[j].copy()
        aug = np.hstack([mat_t, target.reshape(-1, 1)])
        # Row-reduce aug over GF(2)
        rows, cols = aug.shape
        piv_row = 0
        piv_cols = []
        for col in range(cols - 1):
            found = -1
            for r in range(piv_row, rows):
                if aug[r, col] == 1:
                    found = r
                    break
            if found == -1:
                continue
            aug[[piv_row, found]] = aug[[found, piv_row]]
            for r in range(rows):
                if r != piv_row and aug[r, col] == 1:
                    aug[r] ^= aug[piv_row]
            piv_cols.append((piv_row, col))
            piv_row += 1
        sol = np.zeros(cols - 1, dtype=np.uint8)
        for pr, pc in piv_cols:
            sol[pc] = aug[pr, -1]
        m_mat[j] = sol[r_h:]

    is_permutation = bool(
        np.all(np.sum(m_mat, axis=1) == 1) and np.all(np.sum(m_mat, axis=0) == 1)
    )
    is_invertible = gf2_rank(m_mat) == k
    return {
        "matrix": m_mat,
        "is_invertible": is_invertible,
        "is_basis_permutation": is_permutation,
    }
