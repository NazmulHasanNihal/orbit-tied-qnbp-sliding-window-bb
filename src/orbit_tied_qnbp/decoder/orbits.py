"""Automorphism Orbit Extraction and Symmetry Invariance Verifier for BB Codes.

Extracts the torus group action G = Z_l x Z_m on the circuit-level Detector
Error Model (DEM), partitions nodes and hyperedges into symmetry orbits,
classifies window boundary classes, and verifies automorphism invariance.
"""

from typing import List, Tuple, Dict, Set, Any, Optional
import numpy as np
from numpy.typing import NDArray
import stim

from orbit_tied_qnbp.circuits.bivariate_bicycle import BivariateBicycleCode


class DemOrbitManager:
    """Manages automorphism orbits of a Bivariate Bicycle DEM under G = Z_l x Z_m.

    Attributes:
        code: BivariateBicycleCode instance.
        num_rounds: Number of syndrome extraction rounds in the circuit.
        l: Group dimension l.
        m: Group dimension m.
        group_order: Order of G (|G| = l * m).
        det_to_coord: Mapping from detector index to (round, check_type, x, y).
        coord_to_det: Mapping from (round, check_type, x, y) to detector index.
        fault_orbits: Array of orbit IDs for each error mechanism.
        num_fault_orbits: Total distinct fault orbits.
    """

    def __init__(
        self,
        code: BivariateBicycleCode,
        num_rounds: int,
        dem: stim.DetectorErrorModel,
    ) -> None:
        """Initializes the DEM orbit manager and computes symmetry orbits.

        Args:
            code: BivariateBicycleCode instance.
            num_rounds: Number of syndrome extraction rounds.
            dem: Detector Error Model generated by Stim.
        """
        self.code = code
        self.num_rounds = num_rounds
        self.l = code.l
        self.m = code.m
        self.group_order = code.group_order
        self.dem = dem

        self.det_to_coord, self.coord_to_det = self._build_detector_coordinate_maps()
        self.shift_table = self._build_shift_lookup_table()
        self.parsed_errors = self._parse_dem_errors()
        self.fault_orbits, self.num_fault_orbits = self._compute_fault_orbits()

    def _build_shift_lookup_table(self) -> NDArray[np.int64]:
        """Precomputes lookup table of shape (num_detectors, l, m) for O(1) shifts."""
        num_dets = len(self.det_to_coord)
        table = np.zeros((num_dets, self.l, self.m), dtype=np.int64)
        for d in range(num_dets):
            r, ctype, x, y = self.det_to_coord[d]
            for a in range(self.l):
                for b in range(self.m):
                    table[d, a, b] = self.coord_to_det[(r, ctype, (x + a) % self.l, (y + b) % self.m)]
        return table

    def _build_detector_coordinate_maps(
        self,
    ) -> Tuple[Dict[int, Tuple[Any, str, int, int]], Dict[Tuple[Any, str, int, int], int]]:
        """Maps detector index to (round_id, check_type, x, y) and vice versa."""
        d2c: Dict[int, Tuple[Any, str, int, int]] = {}
        c2d: Dict[Tuple[Any, str, int, int], int] = {}
        idx = 0
        g = self.group_order
        m = self.m

        for r in range(self.num_rounds):
            for i in range(g):
                coord = (r, "Z", i // m, i % m)
                d2c[idx] = coord
                c2d[coord] = idx
                idx += 1
            if r > 0:
                for i in range(g):
                    coord = (r, "X", i // m, i % m)
                    d2c[idx] = coord
                    c2d[coord] = idx
                    idx += 1

        for i in range(g):
            coord = ("terminal", "Z", i // m, i % m)
            d2c[idx] = coord
            c2d[coord] = idx
            idx += 1

        return d2c, c2d

    def _parse_dem_errors(
        self,
    ) -> List[Tuple[float, Tuple[int, ...], Tuple[int, ...]]]:
        """Parses error mechanisms (probability, sorted detector symptoms, sorted observables)."""
        errors = []
        for instruction in self.dem:
            if instruction.type == "error":
                p = float(instruction.args_copy()[0])
                dets = []
                obs = []
                for t in instruction.targets_copy():
                    if t.is_relative_detector_id():
                        dets.append(t.val)
                    elif t.is_logical_observable_id():
                        obs.append(t.val)
                errors.append((p, tuple(sorted(dets)), tuple(sorted(obs))))
        return errors

    def shift_detector(self, det: int, a: int, b: int) -> int:
        """Applies spatial torus translation x^a y^b to a detector index in O(1)."""
        return int(self.shift_table[det, a, b])

    def _compute_fault_orbits(self) -> Tuple[NDArray[np.int64], int]:
        """Partitions all error mechanisms into orbits under the action of G."""
        num_errors = len(self.parsed_errors)
        fault_orbits = np.full(num_errors, -1, dtype=np.int64)

        # Index errors by (symptom_tuple, rounded_probability)
        symptom_map: Dict[Tuple[Tuple[int, ...], float], int] = {}
        for idx, (p, dets, _) in enumerate(self.parsed_errors):
            key = (dets, round(p, 12))
            symptom_map[key] = idx

        orbit_counter = 0
        s_table = self.shift_table
        for idx in range(num_errors):
            if fault_orbits[idx] != -1:
                continue
            # Seed new orbit
            current_orbit_id = orbit_counter
            orbit_counter += 1

            p, dets, _ = self.parsed_errors[idx]
            p_rounded = round(p, 12)
            det_len = len(dets)

            for a in range(self.l):
                for b in range(self.m):
                    if det_len == 1:
                        shifted_dets = (int(s_table[dets[0], a, b]),)
                    elif det_len == 2:
                        d0 = int(s_table[dets[0], a, b])
                        d1 = int(s_table[dets[1], a, b])
                        shifted_dets = (d0, d1) if d0 <= d1 else (d1, d0)
                    else:
                        shifted_dets = tuple(sorted(int(s_table[d, a, b]) for d in dets))

                    shifted_key = (shifted_dets, p_rounded)
                    if shifted_key in symptom_map:
                        match_idx = symptom_map[shifted_key]
                        if fault_orbits[match_idx] == -1:
                            fault_orbits[match_idx] = current_orbit_id

        return fault_orbits, orbit_counter

    def verify_automorphisms(self) -> Dict[str, Any]:
        """Verifies that all |G| = l * m torus shifts are strict DEM automorphisms.

        Returns:
            Dictionary containing verification statistics:
                - shifts_tested: Total shifts tested.
                - valid_shifts: Total shifts that preserve DEM error mechanisms.
                - num_errors: Total error mechanisms.
                - num_orbits: Total orbits.
                - compression_ratio: num_errors / num_orbits.

        Raises:
            AssertionError: If any shift fails to preserve DEM symptoms and priors.
        """
        symptom_map: Dict[Tuple[int, ...], List[Tuple[int, float]]] = {}
        for idx, (p, dets, _) in enumerate(self.parsed_errors):
            symptom_map.setdefault(dets, []).append((idx, p))

        num_errors = len(self.parsed_errors)
        valid_shifts = 0

        for a in range(self.l):
            for b in range(self.m):
                matched = 0
                for p, dets, _ in self.parsed_errors:
                    shifted_dets = tuple(sorted([self.shift_detector(d, a, b) for d in dets]))
                    if shifted_dets in symptom_map:
                        candidates = symptom_map[shifted_dets]
                        if any(abs(c_p - p) < 1e-10 for _, c_p in candidates):
                            matched += 1
                if matched == num_errors:
                    valid_shifts += 1
                else:
                    raise AssertionError(
                        f"Shift ({a}, {b}) is not an automorphism! "
                        f"Matched {matched}/{num_errors} error mechanisms."
                    )

        return {
            "shifts_tested": self.group_order,
            "valid_shifts": valid_shifts,
            "num_errors": num_errors,
            "num_orbits": self.num_fault_orbits,
            "compression_ratio": num_errors / max(1, self.num_fault_orbits),
        }

    def classify_window_boundary(
        self, window_start_round: int, window_end_round: int
    ) -> NDArray[np.int8]:
        """Classifies each error mechanism into window classes: 0=open_left, 1=interior, 2=open_right.

        Args:
            window_start_round: Starting syndrome extraction round index.
            window_end_round: Ending syndrome extraction round index.

        Returns:
            1D array of length num_errors containing class labels (0, 1, or 2).
        """
        classes = np.ones(len(self.parsed_errors), dtype=np.int8)  # default: interior (1)
        for idx, (_, dets, _) in enumerate(self.parsed_errors):
            touches_start = False
            touches_end = False
            for d in dets:
                r, _, _, _ = self.det_to_coord[d]
                if r == window_start_round:
                    touches_start = True
                elif r == window_end_round or r == "terminal":
                    touches_end = True
            if touches_start and not touches_end:
                classes[idx] = 0  # open_left
            elif touches_end and not touches_start:
                classes[idx] = 2  # open_right

        return classes
